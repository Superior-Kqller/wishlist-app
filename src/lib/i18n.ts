export function isLanguage(value: string | null | undefined): value is Language {
  return LANGUAGES.includes(value as Language);
}

export function normalizeLanguage(value: string | null | undefined): Language {
  return isLanguage(value) ? value : DEFAULT_LANGUAGE;
}

export function translate(language: Language, key: string): string {
  return dictionaries[language][key] ?? key;
}

export function interpolate(template: string, values?: Record<string, string | number>) {
  if (!values) return template;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function translateWithValues(
  language: Language,
  key: string,
  values?: Record<string, string | number>,
): string {
  return interpolate(translate(language, key), values);
}

export function getLanguageLocale(language: Language): string {
  return languageLocales[language];
}

export function getItemWord(language: Language, count: number): string {
  if (language === "en") return count === 1 ? "item" : "items";
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return "товар";
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "товара";
  return "товаров";
}

export function getCardWord(language: Language, count: number): string {
  if (language === "en") return count === 1 ? "card" : "cards";
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return "карточка";
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "карточки";
  return "карточек";
}
